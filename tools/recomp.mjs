// Generates C for every traced block:
//   generated/recomp_00.c .. recomp_15.c  - block functions plus a per-file table
//   generated/recomp_table.c             - collects the per-file tables
// The file count is fixed so the build system knows the outputs in advance.
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadRom } from './lib/rom.mjs';
import { trace } from './lib/trace.mjs';
import { loadExtraEntries } from './lib/inputs.mjs';
import { genBlock } from './lib/codegen.mjs';

export const CHUNKS = 16;

const rom = loadRom();
const t = trace(rom, loadExtraEntries());
const parts = t.blocks.flatMap((b) => genBlock(rom, b));

const outDir = join(ROOT, 'generated');
mkdirSync(outDir, { recursive: true });

// Only rewrite files whose content changed, so the C build stays incremental.
const writeIfChanged = (path, text) => {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return;
  writeFileSync(path, text);
};

const header = '/* Generated by tools/recomp.mjs from the user\'s ROM. Do not edit or distribute. */\n#include "recomp_rt.h"\n\n';
const per = Math.ceil(parts.length / CHUNKS);
for (let c = 0; c < CHUNKS; c++) {
  const mine = parts.slice(c * per, (c + 1) * per);
  const body = mine.map((p) => p.code).join('\n');
  const table = mine.flatMap((p) => p.entries.map((pc) => `    { 0x${pc.toString(16).toUpperCase()}, ${p.name} },`)).join('\n');
  const id = String(c).padStart(2, '0');
  writeIfChanged(join(outDir, `recomp_${id}.c`), header + body +
    `\nconst RecompEntry recomp_table_${id}[] = {\n${table}\n    { 0, 0 }\n};\n`);
}

const ids = [...Array(CHUNKS).keys()].map((c) => String(c).padStart(2, '0'));
writeIfChanged(join(outDir, 'recomp_table.c'), header +
  ids.map((id) => `extern const RecompEntry recomp_table_${id}[];`).join('\n') +
  `\n\nconst RecompEntry *const recomp_tables[] = {\n${ids.map((id) => `    recomp_table_${id},`).join('\n')}\n    0\n};\n`);

console.log(`recompiled ${parts.length} block functions from ${t.blocks.length} blocks into ${CHUNKS} files`);
